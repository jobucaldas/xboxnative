#!/bin/bash
# sync-readme-versions.sh [--check] [MANIFEST=/workspace/x64-run/kit/latest/manifest.json]
#
# README.md's "Built versions" table is generated from a kit's manifest.json
# (identity + version come from each package's AppxManifest.xml at build time,
# so they cannot drift from what the build produced). Rewrites the block
# between the kit-versions markers; with --check only compares and exits 1 on
# a difference. build-kit.sh runs this after every build.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
mode=write
if [ "${1:-}" = "--check" ]; then mode=check; shift; fi
manifest="${1:-/workspace/x64-run/kit/latest/manifest.json}"
[ -f "$manifest" ] || { echo "sync-readme-versions: $manifest not found" >&2; exit 2; }
python3 - "$mode" "$manifest" "$here/README.md" <<'PY'
import json, sys
mode, manifest, readme = sys.argv[1:4]
begin, end = '<!-- kit-versions:begin (generated by sync-readme-versions.sh) -->', '<!-- kit-versions:end -->'
doc = json.load(open(manifest))
rows = ['| Package | Identity | Version | AppUserModelId (RID) |', '| --- | --- | --- | --- |']
for p in doc['packages']:
    ident = p['identity']
    rows.append(f"| `{p['name']}` | `{ident}` | {p['version']} | `{ident}_dk715arakrne0!App` |")
block = begin + '\n' + '\n'.join(rows) + '\n' + end
text = open(readme).read()
i, j = text.find(begin), text.find(end)
if i < 0 or j < 0:
    sys.exit('sync-readme-versions: markers missing in README.md')
new = text[:i] + block + text[j + len(end):]
if mode == 'check':
    if new != text:
        print('FAIL: README.md version table differs from ' + manifest + ' (run sync-readme-versions.sh)')
        sys.exit(1)
    print('PASS: README.md version table matches ' + manifest)
else:
    open(readme, 'w').write(new)
    print('sync-readme-versions: README.md updated from ' + manifest)
PY
